/**
 * @file PoiSystem.hpp
 * @brief Points of interest come alive: guards, force shields, discovery,
 *        beacon maps, and the 50% charting rule.
 *
 * ============================================================================
 * WHAT IT RUNS (every frame, in a level)
 * ============================================================================
 *   DISCOVERY  a POI goes on the map once the ship's auspex reaches it
 *              (scan radius + its footprint), once a beacon map is decoded
 *              for it, or once half of its sub-zone has been flown.
 *   GUARDS     laid out when the ship comes within 3300 px, at their posts,
 *              leashed there until they see you (EnemyComponent::guardLeash).
 *              Dormant guards (a nest, a distress trap) come up TOGETHER
 *              when the ship gets close or one of them wakes. All guards
 *              gone while you were far = culled, laid out again later; gone
 *              while near = cleared, for good.
 *   SHIELD     `shield` px round the centre: any rock or junk that is NOT the
 *              POI's own is turned away at the edge -- bounced off and
 *              pushed out, with a ripple where it struck. Ships and bullets
 *              are never touched: to them it is fog.
 *   BEACONS    each beacon map picked up is decoded here: the nearest POI
 *              not yet on the map is charted, with 6000 px of fog round it.
 *   50% RULE   once half of a sub-zone cell has been seen, the whole cell is
 *              charted, POIs and all -- exploring is the reward, hunting for
 *              the last corner is not.
 *
 * The POIs themselves are generated by utils/FieldGen (scripts/pois.lua);
 * their structures and loot are placed objects streamed in by EnemySystem.
 *
 * @author Oleg Ivakhiv
 * @version 1.0
 */

#pragma once

#include "ISystem.hpp"
#include "core/EntityManager.hpp"
#include "utils/LevelGen.hpp"
#include "utils/UiPalette.hpp"
#include "systems/EnemySystem.hpp"
#include <SFML/Graphics.hpp>
#include <algorithm>
#include <cmath>
#include <string>
#include <vector>

class PoiSystem : public ISystem {
public:
    void init(const SystemContext& ctx) override {
        m_em = ctx.em;
        m_lua = ctx.lua;
        m_level = ctx.level;
        m_window = ctx.drawTarget();
        m_playerEntityId = ctx.playerEntityId;
        m_ripples.clear();
        m_bannerT = -1.f;
        m_chartT = 0.f;
        m_charted.clear();
        m_lastFog = 0xFFFFFFFFu;
    }
    void setEnemySystem(EnemySystem* e) { m_enemies = e; }
    void setFont(const sf::Font* f) { m_font = f; }

    void update(float dt) override {
        if (!active()) return;
        levelgen::Level& L = m_level->level;
        const size_t pi = m_em->getEntityIndex(m_playerEntityId);
        if (pi == (size_t)-1) return;
        const sf::Vector2f pp = m_em->transforms[pi].position;
        const float scanR = m_level->cfg ? m_level->cfg->scanRadius : 2600.f;
        if (m_charted.size() != L.cells.size()) m_charted.assign(L.cells.size(), 0);

        for (size_t k = 0; k < L.pois.size(); ++k) {
            levelgen::Poi& p = L.pois[k];
            const float d = std::hypot(p.pos.x - pp.x, p.pos.y - pp.y);

            // ---- Discovery by the auspex ----
            if (!p.discovered && d < scanR + p.radius) discover(p, "POI DISCOVERED");

            // ---- Guards ----
            if (p.state == 0 && !p.guards.empty() && d < 3300.f && !m_em->bossArena.active) layOut(k);
            else if (p.state == 0 && p.guards.empty() && d < p.radius) p.state = 2;
            else if (p.state == 1) watchGuards(p, d);

            // ---- The shield ----
            if (p.shield > 0.f && d < p.shield + 3200.f) shield(k);
        }

        // ---- Beacon maps ----
        while (m_em->beaconMaps > 0) { --m_em->beaconMaps; decodeBeacon(pp); }

        // ---- 50%: chart a sub-zone once half of it is seen ----
        m_chartT -= dt;
        if (m_chartT <= 0.f && m_level->fogVersion != m_lastFog) {
            m_chartT = 0.5f;
            m_lastFog = m_level->fogVersion;
            chartHalfSeen();
        }

        for (auto& r : m_ripples) r.t += dt;
        m_ripples.erase(std::remove_if(m_ripples.begin(), m_ripples.end(),
            [](const Ripple& r) { return r.t > 0.6f; }), m_ripples.end());
        if (m_bannerT >= 0.f) { m_bannerT += dt; if (m_bannerT > 3.6f) m_bannerT = -1.f; }
        m_time += dt;
    }

    /// The shield bubbles, in the world view (under the ships).
    void drawWorld() {
        if (!active() || !m_window) return;
        const auto& L = m_level->level;
        const sf::View& v = m_window->getView();
        const sf::Vector2f vc = v.getCenter(), vh = v.getSize() * 0.5f;
        for (const auto& p : L.pois) {
            if (p.shield <= 0.f) continue;
            if (std::fabs(p.pos.x - vc.x) > vh.x + p.shield || std::fabs(p.pos.y - vc.y) > vh.y + p.shield) continue;
            const float breathe = 0.85f + 0.15f * std::sin(m_time * 1.3f + p.pos.x * 0.001f);
            sf::CircleShape c(p.shield, 96);
            c.setOrigin({ p.shield, p.shield });
            c.setPosition(p.pos);
            c.setFillColor(sf::Color(90, 200, 255, static_cast<uint8_t>(10 * breathe)));
            c.setOutlineThickness(3.f);
            c.setOutlineColor(sf::Color(110, 220, 255, static_cast<uint8_t>(46 * breathe)));
            m_window->draw(c);
            sf::CircleShape in(p.shield - 26.f, 96);
            in.setOrigin({ p.shield - 26.f, p.shield - 26.f });
            in.setPosition(p.pos);
            in.setFillColor(sf::Color::Transparent);
            in.setOutlineThickness(1.5f);
            in.setOutlineColor(sf::Color(110, 220, 255, static_cast<uint8_t>(18 * breathe)));
            m_window->draw(in);
        }
        // Where something struck it.
        for (const auto& r : m_ripples) {
            const float a = 1.f - r.t / 0.6f;
            const float rad = 30.f + r.t * 160.f;
            sf::CircleShape c(rad, 24);
            c.setOrigin({ rad, rad });
            c.setPosition(r.at);
            c.setFillColor(sf::Color::Transparent);
            c.setOutlineThickness(2.5f);
            c.setOutlineColor(sf::Color(160, 235, 255, static_cast<uint8_t>(170 * a)));
            m_window->draw(c);
        }
    }

    /// "POI DISCOVERED // OUTPOST" and friends. Screen space.
    void drawHud(sf::Vector2f ws) {
        if (!active() || m_bannerT < 0.f || !m_font || !m_window) return;
        const float a = std::clamp(std::min(m_bannerT / 0.25f, (3.6f - m_bannerT) / 0.6f), 0.f, 1.f);
        const float y = ws.y * 0.36f;
        ui::label(*m_window, m_font, ws.x * 0.5f - textW(m_banner, 16) * 0.5f, y, m_banner, 16,
            sf::Color(255, 205, 110, static_cast<uint8_t>(255 * a)));
        if (!m_bannerSub.empty())
            ui::label(*m_window, m_font, ws.x * 0.5f - textW(m_bannerSub, 12) * 0.5f, y + 26.f, m_bannerSub, 12,
                sf::Color(200, 200, 210, static_cast<uint8_t>(220 * a)));
    }

private:
    bool active() const { return m_em && m_level && m_level->active; }

    float textW(const std::string& s, unsigned size) const {
        return ui::labelWidth(m_font, s, size);
    }

    static std::string upper(std::string s) { for (auto& ch : s) ch = static_cast<char>(std::toupper(static_cast<unsigned char>(ch))); return s; }

    void banner(const std::string& head, const std::string& sub, const char* sound) {
        m_banner = head;
        m_bannerSub = sub;
        m_bannerT = 0.f;
        if (sound) m_em->sfxUi(sound);
    }

    void discover(levelgen::Poi& p, const char* how) {
        if (p.discovered) return;
        p.discovered = true;
        ++m_level->fogVersion;   // the map caches repaint
        banner(how, upper(p.display), "hud.poi.discovered");
    }

    // ---- Guards ---------------------------------------------------------
    void layOut(size_t k) {
        levelgen::Poi& p = m_level->level.pois[k];
        p.guardIds.clear();
        if (!m_enemies) return;
        const size_t n = p.guards.size();
        const uint32_t link = m_em->newLinkGroup();   // hit one guard, the whole post answers
        for (size_t g = 0; g < n; ++g) {
            const bool sleeps = p.guardsDormant || (g < p.guardSleeps.size() && p.guardSleeps[g]);
            const float a = (g + 0.4f) * 6.2831853f / std::max<size_t>(1, n) + (rand() % 100) / 200.f;
            // Sleepers lie in close (a docked Barge at its station); the rest stand guard further out.
            const float r = p.radius * (sleeps && !p.guardsDormant ? 0.42f : 0.55f + (rand() % 40) / 100.f);
            sf::Vector2f at = p.pos + sf::Vector2f(std::cos(a), std::sin(a)) * r;
            if (!m_level->spawnable(at, 400.f, 90.f)) at = p.pos + sf::Vector2f(std::cos(a), std::sin(a)) * (p.radius + 160.f);
            // `at_centre`: the lead holds the middle (the Dreadnought).
            if (g == 0 && (*m_lua)["poi_types"][p.type]["guards"]["at_centre"].get_or(false)) at = p.pos;
            const uint32_t id = m_enemies->summon(p.guards[g], at, sleeps);
            if (!id) continue;
            const size_t i = m_em->getEntityIndex(id);
            if (i == (size_t)-1) continue;
            auto& ec = m_em->enemies[i];
            ec.linkGroup = link;
            ec.guardHome = at;
            ec.guardLeash = p.guardLeash;
            if (g < p.guardLoot.size() && p.guardLoot[g]) {
                sol::optional<sol::table> lg = (*m_lua)["poi_types"][p.type]["loot_guard"];
                ec.lootScale = lg ? (*lg)["scrap"].get_or(2.5f) : 2.5f;
                ec.lootKitChance = lg ? (*lg)["kit"].get_or(0.6f) : 0.6f;
                ec.lootBeaconChance = lg ? (*lg)["beacon"].get_or(0.5f) : 0.5f;
            }
            if (sleeps) m_enemies->settleLikeWreck(id, (rand() % 360) * 1.f);
            p.guardIds.push_back(id);
        }
        p.state = 1;
    }

    void watchGuards(levelgen::Poi& p, float d) {
        bool anyAlive = false, anyAwake = false;
        for (uint32_t id : p.guardIds) {
            const size_t i = m_em->getEntityIndex(id);
            if (i == (size_t)-1) continue;
            anyAlive = true;
            // "Awake" = fighting: a guard merely standing post does not wake the sleepers.
            if (!m_em->enemies[i].dormant && m_em->enemies[i].visualState == EnemyState::COMBAT) anyAwake = true;
        }
        if (!anyAlive) {
            if (d > 6000.f) p.state = 0;     // culled while you were away: lay them out again
            else {
                p.state = 2;                 // you cleared it
                banner("POI CLEARED", upper(p.display), "hud.poi.cleared");
            }
            return;
        }
        // Sleepers come up together: close enough, or one of them is up.
        if (d < p.radius * (p.guardsDormant ? 0.9f : 0.45f) || anyAwake)
            for (uint32_t id : p.guardIds) {
                const size_t i = m_em->getEntityIndex(id);
                if (i != (size_t)-1 && m_em->enemies[i].dormant) m_em->enemies[i].provoked = true;
            }
    }

    // ---- Shield -----------------------------------------------------------
    void shield(size_t k) {
        const levelgen::Poi& p = m_level->level.pois[k];
        const auto& L = m_level->level;
        const float R = p.shield;
        for (size_t i = 0; i < m_em->physics.size(); ++i) {
            const b2BodyId b = m_em->physics[i].bodyId;
            if (!b2Body_IsValid(b)) continue;
            const BodyUserData* ud = bodyUD(b);
            if (!ud || ud->type != BodyType::Asteroid) continue;
            // The POI's own objects live inside it.
            auto it = m_level->placedById.find(m_em->transforms[i].entityId);
            if (it != m_level->placedById.end() && L.placed[static_cast<size_t>(it->second)].poi == static_cast<int>(k)) continue;
            const sf::Vector2f q = m_em->transforms[i].position;
            const sf::Vector2f d = q - p.pos;
            const float dl = std::sqrt(d.x * d.x + d.y * d.y);
            const float r = i < m_em->healths.size() ? m_em->healths[i].visualRadius : 20.f;
            if (dl > R + r || dl < 1.f) continue;
            const sf::Vector2f n = d / dl;
            b2Vec2 v = b2Body_GetLinearVelocity(b);
            const float vn = v.x * n.x + v.y * n.y;
            if (vn < 0.f) {   // heading in: bounce it off
                v.x -= 1.6f * vn * n.x;
                v.y -= 1.6f * vn * n.y;
                b2Body_SetLinearVelocity(b, v);
                if (m_ripples.size() < 24) m_ripples.push_back({ p.pos + n * R, 0.f });
                if (rand() % 3 == 0) m_em->sfx("shield.deflect", p.pos + n * R, 0.6f);
            }
            // Pushed back out to the edge (it was born inside, or shoved in).
            const sf::Vector2f out = p.pos + n * (R + r + 2.f);
            b2Body_SetTransform(b, { out.x / SCALE, out.y / SCALE }, b2Body_GetRotation(b));
            m_em->transforms[i].position = out;
        }
    }

    // ---- Beacon maps ----------------------------------------------------------
    void decodeBeacon(sf::Vector2f pp) {
        auto& L = m_level->level;
        int best = -1; float bd = 1e30f;
        for (size_t k = 0; k < L.pois.size(); ++k) {
            if (L.pois[k].discovered) continue;
            const float d = std::hypot(L.pois[k].pos.x - pp.x, L.pois[k].pos.y - pp.y);
            if (d < bd) { bd = d; best = static_cast<int>(k); }
        }
        const float r = (*m_lua)["poi_beacon_reveal"].get_or(6000.f);
        if (best < 0) {
            // Nothing left to find: it charts the nearest unseen ground instead.
            m_level->reveal(pp, r * 0.6f);
            banner("BEACON DECODED", "NOTHING NEW ON THIS SECTOR'S CHARTS", "hud.beacon.decoded");
            return;
        }
        auto& p = L.pois[static_cast<size_t>(best)];
        m_level->reveal(p.pos, r);
        p.discovered = true;
        ++m_level->fogVersion;
        banner("BEACON DECODED", upper(p.display) + " CHARTED", "hud.beacon.decoded");
    }

    // ---- The 50% rule ------------------------------------------------------------
    void chartHalfSeen() {
        auto& L = m_level->level;
        const float h = L.cellSize * 0.5f;
        const float share = (*m_lua)["poi_chart_share"].get_or(0.5f);
        for (size_t ci = 0; ci < L.cells.size(); ++ci) {
            if (m_charted[ci]) continue;
            const sf::Vector2f c = L.cellCentre(static_cast<int>(ci));
            int seen = 0, total = 0;
            const float fc = m_level->fogCell;
            const int x0 = std::max(0, static_cast<int>((c.x - h - m_level->fogOrigin.x) / fc));
            const int x1 = std::min(m_level->fogW - 1, static_cast<int>((c.x + h - m_level->fogOrigin.x) / fc));
            const int y0 = std::max(0, static_cast<int>((c.y - h - m_level->fogOrigin.y) / fc));
            const int y1 = std::min(m_level->fogH - 1, static_cast<int>((c.y + h - m_level->fogOrigin.y) / fc));
            for (int y = y0; y <= y1; ++y)
                for (int x = x0; x <= x1; ++x) {
                    const sf::Vector2f q = m_level->fogOrigin + sf::Vector2f((x + 0.5f) * fc, (y + 0.5f) * fc);
                    if (!L.inside(q, 0.f)) continue;   // the Void does not count
                    ++total;
                    if (m_level->seen(x, y)) ++seen;
                }
            if (total == 0 || seen < total * share) continue;
            // Chart it: every fog cell of it, its name, its POIs.
            m_charted[ci] = 1;
            for (int y = y0; y <= y1; ++y)
                for (int x = x0; x <= x1; ++x) m_level->fog[static_cast<size_t>(y) * m_level->fogW + x] = 1;
            if (ci < m_level->cellVisited.size()) m_level->cellVisited[ci] = 1;
            int found = 0;
            for (auto& p : L.pois) if (p.cell == static_cast<int>(ci) && !p.discovered) { p.discovered = true; ++found; }
            ++m_level->fogVersion;
            m_lastFog = m_level->fogVersion;
            std::string sub = found == 1 ? "1 POINT OF INTEREST CHARTED"
                : found > 1 ? std::to_string(found) + " POINTS OF INTEREST CHARTED" : "";
            banner("SUB-ZONE CHARTED", sub, "hud.zone.charted");
        }
    }

    struct Ripple { sf::Vector2f at; float t = 0.f; };

    EntityManager* m_em = nullptr;
    sol::state* m_lua = nullptr;
    levelgen::LevelState* m_level = nullptr;
    sf::RenderTarget* m_window = nullptr;
    EnemySystem* m_enemies = nullptr;
    const sf::Font* m_font = nullptr;
    uint32_t m_playerEntityId = 0;
    std::vector<Ripple> m_ripples;
    std::vector<char> m_charted;
    uint32_t m_lastFog = 0xFFFFFFFFu;
    float m_chartT = 0.f;
    float m_time = 0.f;
    std::string m_banner, m_bannerSub;
    float m_bannerT = -1.f;
};
